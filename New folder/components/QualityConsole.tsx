function normalizeEvidenceLine(line: string) {
  const trimmed = line.trim();
  if (!trimmed) return null;
  if (trimmed.startsWith("Executed SQL:")) return null;
  if (/^\{.*\}$/.test(trimmed)) return "Structured log event captured during this run.";
  if (trimmed.length > 220) return `${trimmed.slice(0, 217).trimEnd()}...`;
  return trimmed;
}

function summarizeEvidence(evidence: string[]) {
  const normalized = evidence
    .map(normalizeEvidenceLine)
    .filter((line): line is string => Boolean(line));

  if (!normalized.length) {
    return ["Execution summary available in the command preview."];
  }

  return Array.from(new Set(normalized)).slice(0, 3);
}

function DonutStat({
  label,
  value,
  total,
  colorClass,
}: {
  label: string;
  value: number;
  total: number;
  colorClass: string;
}) {
  const radius = 30;
  const circumference = 2 * Math.PI * radius;
  const percent = total ? Math.round((value / total) * 100) : 0;
  const dashoffset = circumference - (percent / 100) * circumference;

  return (
    <div className="rounded-[26px] border border-slate-200 bg-white p-5">
      <div className="flex items-center gap-4">
        <div className="relative h-[88px] w-[88px] shrink-0">
          <svg viewBox="0 0 88 88" className="h-[88px] w-[88px] -rotate-90">
            <circle cx="44" cy="44" r={radius} fill="none" stroke="#e2e8f0" strokeWidth="8" />
            <circle
              cx="44"
              cy="44"
              r={radius}
              fill="none"
              stroke="currentColor"
              strokeWidth="8"
              strokeLinecap="round"
              strokeDasharray={circumference}
              strokeDashoffset={dashoffset}
              className={colorClass}
            />
          </svg>
          <div className="absolute inset-0 flex flex-col items-center justify-center">
            <span className="text-lg font-semibold text-slate-900">{percent}%</span>
            <span className="text-[10px] uppercase tracking-[0.18em] text-slate-400">share</span>
          </div>
        </div>
        <div>
          <p className="text-xs font-medium uppercase tracking-[0.18em] text-slate-400">{label}</p>
          <p className="mt-1 text-2xl font-semibold text-slate-950">{value}</p>
          <p className="mt-1 text-sm text-slate-500">
            {value} of {Math.max(total, 1)} active runs
          </p>
        </div>
      </div>
    </div>
  );
}

